import { chromium } from "playwright-core";
import { spawn } from "node:child_process";
const port = 18000 + Math.floor(Math.random() * 1000);
const server = spawn(process.execPath, ["apps/web/test/serve.mjs", String(port)], { stdio: "ignore" });
await new Promise((r) => setTimeout(r, 400));
const cache = process.cwd() + "/web/test/.cache";
const b = await chromium.launch({ executablePath: "/usr/bin/chromium", args: ["--no-sandbox", "--disable-crashpad", "--disable-crash-reporter"], env: { ...process.env, HOME: cache, XDG_CONFIG_HOME: cache + "/cfg", XDG_CACHE_HOME: cache + "/cache" } });
const p = await b.newPage({ viewport: { width: 1360, height: 820 } });
p.on("pageerror", (e) => console.log("PAGEERROR", e.stack));
p.on("console", (m) => /error|warn/.test(m.type()) && console.log(m.type(), m.text().slice(0, 300)));
await p.goto(`http://127.0.0.1:${port}/`);
const shadow = (js) => `(() => { const r = document.querySelector("phitex-preview")?.shadowRoot; if (!r) return false; ${js} })()`;
await p.waitForFunction(shadow(`return r.querySelectorAll(".slot canvas").length > 0`), null, { timeout: 120000 });
await p.waitForTimeout(1500);
console.log("step add");
await p.click(".phx-tree-head [data-act=new]");
await p.fill(".phx-tree-name input", "intro.tex");
await p.press(".phx-tree-name input", "Enter");
await p.waitForTimeout(300);
console.log("editor file:", await p.evaluate(() => document.querySelector(".phx-tree-list li.on")?.dataset.path));
await p.click(".cm-content");
await p.keyboard.type("\\section{Second} Wordfromintro.", { delay: 20 });
await p.waitForTimeout(1500);
console.log("step main");
await p.click('.phx-tree-list li[data-path="main.tex"] .name');
await p.waitForTimeout(300);
await p.evaluate(() => 0);
const n = await p.locator(".cm-line").count();
console.log("lines", n);
await p.click(`.cm-line >> nth=${n - 3}`); await p.keyboard.press("End");
await p.keyboard.type("\n\\input{intro}", { delay: 40 });
await p.waitForTimeout(6000);
console.log("problems:", await p.evaluate(() => document.querySelector("phitex-preview").shadowRoot.getElementById("sum")?.textContent));
console.log("text has it:", await p.evaluate(shadow(`return [...r.querySelectorAll(".slot text")].some((t) => t.textContent.includes("Wordfromintro"))`)));
await p.screenshot({ path: "apps/web/shots/multi-debug.png" });
await b.close(); server.kill();
